#Exercício seis: Área e perímetro do retângulo

largura = float(input("Digite a largura do seu retângulo: "))
altura = float(input("Digite a altura do seu retângulo: "))

area = largura * altura
perimetro = 2 * (largura + altura)

print(f"A área do seu triangulo é {area}, e o perimetro é {perimetro}") 