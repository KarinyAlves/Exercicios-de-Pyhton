#Exercício quatro: Leia um número real e mostre o dobro, o triplo e a metade desse valor

numero = float(input("Digite um número para saber qual o dobro, o triplo e a metade deste: "))

dobro = numero * 2
triplo = numero * 3
metade = numero / 2

print(f"O dobro do número {numero} é {dobro}, o triplo é {triplo} e a metade é {metade}")