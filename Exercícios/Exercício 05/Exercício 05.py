#Exercício 05 - Conversão de medidas

metros = float(input("Digite a medida, em metros, que você deseja converter em centímetros e em milímetros: "))

centimetros = metros * 100
milímetros = metros * 1000


print(f"A medida de {metros} metros, corresponde a {centimetros} centimetros e a {milímetros} milímetros")