#Exercício três: Leia um número inteiro e mostre seu antecessor e seu sucessor

número = int(input("Digite um número para saber seu antecessor e sucessor: "))

Sucessor = número + 1
Número = número
Antecessor = número - 1

print(f"Antecessor: {Antecessor}, Número: {número}, Sucessor: {Sucessor}")